def calculate_api_costs(
    results_df,
    num_images,
    avg_input_tokens=460,
    avg_output_tokens=150
):
    """
    Estimate total API usage cost.

    NOTE:
    Token counts are estimated unless actual API usage
    values are recorded during inference.
    """

    if num_images == 0:

        return {
            "num_images": 0,
            "total_input_tokens": 0,
            "total_output_tokens": 0,
            "total_tokens": 0,
            "input_cost": 0,
            "output_cost": 0,
            "total_cost": 0,
            "cost_per_image": 0
        }

    # ------------------------------------------------------------------------
    # Estimated Token Usage
    # ------------------------------------------------------------------------
    total_input_tokens = (
        num_images * avg_input_tokens
    )

    total_output_tokens = (
        num_images * avg_output_tokens
    )

    # ------------------------------------------------------------------------
    # Cost Calculation
    # ------------------------------------------------------------------------
    input_cost = (
        total_input_tokens / 1000
    ) * MODEL_PRICING["input_cost_per_1k"]

    output_cost = (
        total_output_tokens / 1000
    ) * MODEL_PRICING["output_cost_per_1k"]

    total_cost = (
        input_cost + output_cost
    )

    cost_per_image = (
        total_cost / num_images
    )

    return {

        "num_images":
            num_images,

        "total_input_tokens":
            total_input_tokens,

        "total_output_tokens":
            total_output_tokens,

        "total_tokens":
            total_input_tokens + total_output_tokens,

        "input_cost":
            input_cost,

        "output_cost":
            output_cost,

        "total_cost":
            total_cost,

        "cost_per_image":
            cost_per_image
    }


