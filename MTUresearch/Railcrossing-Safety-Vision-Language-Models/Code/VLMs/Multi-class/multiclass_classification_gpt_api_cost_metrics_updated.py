def zero_shot_predict_gpt(image_path, class_prompts_dict, show_image=False, temperature=0.0):
    """
    Performs zero-shot multiclass classification using GPT-4o-mini.

    """

    if not openai_client:
        return None, 0.0, {}, {}

    try:
        # ------------------------------------------------------------
        # 1. Load and encode image
        # ------------------------------------------------------------
        image = Image.open(image_path).convert("RGB")

        buffered = BytesIO()
        image.save(buffered, format="JPEG")

        img_base64 = base64.standard_b64encode(
            buffered.getvalue()
        ).decode("utf-8")

        # ------------------------------------------------------------
        # 2. Build multiclass prompt directly from class_prompts_dict
        # ------------------------------------------------------------
        class_text = "\n".join(
            [
                f"{label}: {description}"
                for label, description in class_prompts_dict.items()
            ]
        )

        prompt_text = f"""
You are a zero-shot image classifier for railroad-crossing scenes.

Classify the provided image into EXACTLY ONE of the following classes:

{class_text}

Instructions:
- Select only one class.
- Use the class descriptions above to determine the best matching class.
- Return ONLY the class label.
- Do not provide explanations.
- Do not return Yes/No.
- Do not return multiple classes.

Valid outputs are exactly:
{", ".join(class_prompts_dict.keys())}

"""

        # ------------------------------------------------------------
        # 3. Call GPT API
        # ------------------------------------------------------------
        response = openai_client.chat.completions.create(
            model="gpt-4o-mini",
            temperature=temperature,
            max_tokens=30,
            messages=[
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "text",
                            "text": prompt_text
                        },
                        {
                            "type": "image_url",
                            "image_url": {
                                "url": f"data:image/jpeg;base64,{img_base64}"
                            }
                        }
                    ]
                }
            ]
        )

        # ------------------------------------------------------------
        # 4. Extract response
        # ------------------------------------------------------------
        output_text = response.choices[0].message.content.strip()

        # ------------------------------------------------------------
        # 5. Match response to valid class
        # ------------------------------------------------------------
        predicted_class = None

        # Exact match first
        for class_name in class_prompts_dict.keys():
            if output_text.lower() == class_name.lower():
                predicted_class = class_name
                break

        # Fallback if GPT adds minor extra text
        if predicted_class is None:
            for class_name in class_prompts_dict.keys():
                if class_name.lower() in output_text.lower():
                    predicted_class = class_name
                    break

        # Parsing failure
        if predicted_class is None:
            print(f"⚠️ Could not parse GPT response: {output_text}")

            return None, 0.0, {}, {
                "raw_response": output_text
            }

        # ------------------------------------------------------------
        # 6. No calibrated probability is provided
        # ------------------------------------------------------------
        class_scores = {
            class_name: 1.0 if class_name == predicted_class else 0.0
            for class_name in class_prompts_dict.keys()
        }

        predicted_confidence = 1.0

        response_dict = {
            "raw_response": output_text,
            "predicted_class": predicted_class
        }

        # ------------------------------------------------------------
        # 7. Optional visualization
        # ------------------------------------------------------------
        if show_image:
            plt.imshow(image)
            plt.axis("off")
            plt.title(f"GPT-4o-mini Prediction: {predicted_class}")
            plt.show()

            print(f"Predicted Class: {predicted_class}")

        return (
            predicted_class,
            predicted_confidence,
            class_scores,
            response_dict
        )

    except Exception as e:
        print(f"❌ GPT error: {e}")
        return None, 0.0, {}, {}

def evaluate_model(
    model_name,
    predict_fn,
    image_paths,
    class_prompts_dict
):
    """
    Evaluate a model on all images.

    Args:
        model_name: Name of the model
        predict_fn: Prediction function
        image_paths: List of image paths
        class_prompts_dict: Dictionary mapping class labels to descriptions

    Returns:
        tuple: (summary_dict, results_dataframe)
    """

    print(f"\n🔎 Evaluating {model_name}...")
    print(f"{'─' * 80}")

    predictions = []
    confidences = []
    errors = 0

    # ------------------------------------------------------------
    # Run predictions
    # ------------------------------------------------------------
    for i, img_path in enumerate(image_paths, 1):

        try:
            pred, conf, _, _ = predict_fn(
                img_path,
                class_prompts_dict
            )

            if pred is None:
                pred = "ERROR"
                conf = 0.0
                errors += 1

            predictions.append(pred)
            confidences.append(
                conf if conf else 0.0
            )

            # Progress
            if i % 50 == 0 or i == len(image_paths):
                print(
                    f"  ✅ {i}/{len(image_paths)} processed"
                )

        except Exception as e:
            predictions.append("ERROR")
            confidences.append(0.0)
            errors += 1

    # ------------------------------------------------------------
    # Create results DataFrame
    # ------------------------------------------------------------
    results_df = pd.DataFrame({
        "Model": [model_name] * len(image_paths),

        "Image": [
            os.path.basename(p)
            for p in image_paths
        ],

        "Image_Path": image_paths,

        "Prediction": predictions,

        "Confidence": confidences
    })

    # ------------------------------------------------------------
    # Valid prediction statistics
    # ------------------------------------------------------------
    successful = (
        results_df["Prediction"] != "ERROR"
    ).sum()

    success_rate = (
        successful / len(image_paths) * 100
        if len(image_paths) > 0
        else 0
    )

    # ------------------------------------------------------------
    # Prediction distribution
    # ------------------------------------------------------------
    pred_counts = (
        results_df["Prediction"]
        .value_counts()
    )

    print(f"\n✅ {model_name} Results:")

    print(
        f"  • Valid Predictions: "
        f"{successful}/{len(image_paths)} "
        f"({success_rate:.1f}%)"
    )

    print("  • Prediction distribution:")

    for pred, count in pred_counts.items():

        if pred != "ERROR":

            pct = (
                count / successful * 100
                if successful > 0
                else 0
            )

            print(
                f"    - {pred}: "
                f"{count} ({pct:.1f}%)"
            )

    # ------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------
    summary = {
        "Model": model_name,
        "Total_Images": len(image_paths),
        "Valid_Predictions": successful,
        "Parsing_Success_Rate": f"{success_rate:.1f}%"
    }

    return summary, results_df

